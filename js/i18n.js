(function initLang() {
  const saved = localStorage.getItem('monsallve_lang');
  if (saved === 'es' || saved === 'en') {
    window.currentLang = saved;
    return;
  }
  const nav = (navigator.language || 'es').toLowerCase();
  window.currentLang = nav.startsWith('en') ? 'en' : 'es';
})();

window.t = function t(key) {
  const pack = window.I18N[window.currentLang] || window.I18N.es;
  return pack[key] || window.I18N.es[key] || key;
};

window.setLang = function setLang(lang) {
  if (!window.I18N[lang]) return;
  window.currentLang = lang;
  localStorage.setItem('monsallve_lang', lang);
  document.documentElement.lang = lang;
  window.applyI18n();
};

window.applyI18n = function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const val = window.t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') return;
    el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', window.t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', window.t(el.getAttribute('data-i18n-title')));
  });
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === window.currentLang);
  });
};

document.addEventListener('DOMContentLoaded', function () {
  document.documentElement.lang = window.currentLang || 'es';
  window.applyI18n();
});
